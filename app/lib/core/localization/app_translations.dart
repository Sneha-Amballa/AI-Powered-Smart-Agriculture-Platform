  /// Translate key according to given language code. Falls back to English, then to key itself.
  static String translate(String key, [AppLanguage? language]) {
    final langCode = language?.code ?? 'en';
    final langMap = _localizedValues[langCode];
    if (langMap != null && langMap.containsKey(key)) {
      return langMap[key]!;
    }
    final enMap = _localizedValues['en'];
    if (enMap != null && enMap.containsKey(key)) {
      return enMap[key]!;
    }
    return key;
  }
